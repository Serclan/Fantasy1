    private void cargarImagenesJugadores() {
        // Imagen local (Mbappe incluida en el proyecto)
        try {
            java.awt.Image img = null;
            java.net.URL localUrl = getClass().getResource("/fantasy/imagenes/mbappe.jpg");
            if (localUrl != null) {
                img = javax.imageio.ImageIO.read(localUrl);
            }
            if (img == null) {
                java.io.File f = new java.io.File("src/fantasy/imagenes/mbappe.jpg");
                if (f.exists()) {
                    img = javax.imageio.ImageIO.read(f);
                }
            }
            if (img != null) {
                jLabel2.setIcon(new javax.swing.ImageIcon(img.getScaledInstance(36, 36, java.awt.Image.SCALE_SMOOTH)));
                jLabel2.setHorizontalTextPosition(javax.swing.SwingConstants.RIGHT);
            }
        } catch (Exception e) {
            logger.log(java.util.logging.Level.INFO, "No se pudo cargar foto local de Mbappe", e);
        }

        // Imagenes remotas desde URL de internet (Lev Yashin, Vidic, Modric, Sorloth)
        new Thread(() -> {
            cargarImagenRemotaParaLabel("https://cdn-img.staticzz.com/img/planteis/new/36/32/763632_nemanja_vidic_20240619235614.jpg", jLabel6);
            cargarImagenRemotaParaLabel("https://cdn-img.staticzz.com/img/jogadores/new/68/72/26872_luka_modric_20251228125156.png", jLabel3);
            cargarImagenRemotaParaLabel("https://encrypted-tbn0.gstatic.com/images?q=tbn:ANd9GcQELUeU-9hXQUjc3yIU81x_Sm5mrGpP_d3buStP7PKxMQYZEb4yl7WAGMk1&s=10", jLabel4);
            cargarImagenRemotaParaLabel("https://encrypted-tbn0.gstatic.com/images?q=tbn:ANd9GcQEGrsAhTXGvtYqk0N5NJ2hpKhshJEmEM62zaNgPWWnKg&s=10", jLabel5);
        }).start();
    }

    private void cargarImagenRemotaParaLabel(String urlString, javax.swing.JLabel label) {
        try {
            java.net.URL url = new java.net.URI(urlString).toURL();
            java.net.HttpURLConnection conn = (java.net.HttpURLConnection) url.openConnection();
            conn.setRequestProperty("User-Agent", "Mozilla/5.0");
            conn.setConnectTimeout(5000);
            conn.setReadTimeout(5000);
            java.awt.Image img = javax.imageio.ImageIO.read(conn.getInputStream());
            if (img != null) {
                javax.swing.ImageIcon icon = new javax.swing.ImageIcon(img.getScaledInstance(36, 36, java.awt.Image.SCALE_SMOOTH));
                javax.swing.SwingUtilities.invokeLater(() -> {
                    label.setIcon(icon);
                    label.setHorizontalTextPosition(javax.swing.SwingConstants.RIGHT);
                });
            }
        } catch (Exception ex) {
            logger.log(java.util.logging.Level.INFO, "No se pudo cargar imagen remota: " + ex.getMessage());
        }
    }

