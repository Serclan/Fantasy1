    private void mostrarDialogo(String titulo, String mensaje, javax.swing.Icon icono) {
        javax.swing.JDialog dialogo = new javax.swing.JDialog(this, titulo, true);
        dialogo.setLayout(new java.awt.FlowLayout(java.awt.FlowLayout.CENTER, 15, 15));
        dialogo.getContentPane().setBackground(new Color(30, 30, 44));

        javax.swing.JLabel lbl = new javax.swing.JLabel(mensaje);
        if (icono != null) {
            lbl.setIcon(icono);
            lbl.setHorizontalTextPosition(javax.swing.SwingConstants.RIGHT);
        }
        lbl.setForeground(java.awt.Color.WHITE);
        lbl.setFont(new java.awt.Font("Segoe UI", java.awt.Font.BOLD, 13));
        dialogo.add(lbl);

        javax.swing.JButton btnAceptar = new javax.swing.JButton("Aceptar");
        btnAceptar.setBackground(java.awt.Color.RED);
        btnAceptar.setForeground(java.awt.Color.WHITE);
        btnAceptar.addActionListener(e -> dialogo.dispose());
        dialogo.add(btnAceptar);

        dialogo.setSize(340, 140);
        dialogo.setResizable(false);
        dialogo.setLocationRelativeTo(this);
        dialogo.setVisible(true);
    }
    
